def toy_embeddings(contig: Path) -> pd.DataFrame: # this is after the encoding step, for clustering.
    seq = pyfastx.Fasta(str(contig), build_index=False)
    n_contigs = len([s for s in seq])
    namelist = [s for s,_ in seq]
    x = rng().normal(size=(n_contigs, 128)).astype("float32")
    x /= np.linalg.norm(x, axis=1, keepdims=True)
    # assume we have 16 contigs, and each contig is represented by a 128-dim embedding vector.
    return pd.DataFrame(x, index=namelist)

def toy_features(n_cov: int, view_num: int = 6,
                simclr: bool = False, 
    ) -> pd.DataFrame:
    x = rng().normal(size=(30, KMER_FEATURE_DIM + 2*n_cov)).astype("float32")
    x /= np.linalg.norm(x, axis=1, keepdims=True)
    
    columns = [f"{i}" for i in range(KMER_FEATURE_DIM)] + [f"cov_{i}_mean" for i in range(n_cov)] + [f"cov_{i}_std" for i in range(n_cov)]
    # index will be 5 contigs with 6 views each.
    if simclr:
        index = [f"contig_{i}.{j}" for i in range(5) for j in range(view_num)]
    else:
        index = [f"contig_{i}.original" for i in range(5)] + [f"contig_{i}.{j}" for i in range(5) for j in range(view_num-1)]
    return pd.DataFrame(x, index=index, columns=columns)

